"""VigilAC dataset pipeline — core library (stdlib only).

This module implements ingestion validation, deduplication, deterministic
group splitting (by player, never by window) and model-agnostic metric
computation for the AI-assist corpus. It contains NO gameplay data.

Honesty contract (enforced here, repeated in every report):

- No synthetic sample in this repository may be presented as real gameplay.
  Files under tests/fixtures/ are synthetic test fixtures only.
- CHEAT_VERIFIED requires label_source CONTROLLED_LAB or MODERATOR_REVIEW
  and label_confidence >= 0.8. SUSPICIOUS rows are excluded from evaluation.
- Metrics are printed only when minimum corpus gates are met
  (>= 200 usable rows, >= 50 CHEAT_VERIFIED, >= 50 LEGITIMATE), unless the
  caller passes --allow-tiny-fixture, in which case every report is stamped
  FIXTURE_ONLY and is meaningless for detection quality.
- Unknown values are rejected, never imputed. Missing features are rejected.

Corpus layout: a directory of *.jsonl files (one JSON object per line),
plus dataset-manifest.json and splits.json when generated by the tools.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, Iterator

SCHEMA_NAMES = [
    "combat.cps_1s", "combat.cps_5s", "combat.click_interval_cv",
    "combat.click_interval_mean_ms", "combat.click_interval_stddev_ms",
    "combat.click_interval_entropy_bits", "combat.distinct_targets_10s",
    "combat.swing_rate_1s",
    "rotation.angular_velocity_dps_1s", "rotation.max_delta_deg_1s",
    "rotation.window_samples",
    "reach.ema_blocks", "reach.sample_count",
    "packet.pps", "packet.raw_move_pps", "packet.move_pps", "movement.airborne_ms",
    "break.interval_ms_clipped", "break.impossible_streak",
    "context.ping_ms", "context.tps_1m", "context.on_ground",
]
FEATURE_COUNT = len(SCHEMA_NAMES)
RANGES = [
    (0.0, 50.0), (0.0, 50.0), (0.0, 5.0), (0.0, 10_000.0), (0.0, 10_000.0),
    (0.0, 16.0), (0.0, 32.0), (0.0, 50.0),
    (0.0, 5_000.0), (0.0, 180.0), (0.0, 64.0),
    (0.0, 8.0), (0.0, 100_000.0),
    (0.0, 400.0), (0.0, 400.0), (0.0, 400.0), (0.0, 3_600_000.0),
    (0.0, 60_000.0), (0.0, 100.0),
    (0.0, 5_000.0), (0.0, 20.0), (0.0, 1.0),
]
SCHEMA_HASH = hashlib.sha256(",".join(SCHEMA_NAMES).encode("utf-8")).hexdigest()

LABELS = ("LEGITIMATE", "CHEAT_VERIFIED", "SUSPICIOUS")
LABEL_SOURCES = ("CONTROLLED_LAB", "MODERATOR_REVIEW", "SERVER_TELEMETRY_CURATION", "HEURISTIC_FLAG")
INPUT_CATEGORIES = ("MOUSE", "KEYBOARD", "MIXED", "CONTROLLER", "UNKNOWN")
PSEUDONYM_RE = re.compile(r"^[0-9a-f]{16,64}$")
MC_VERSION_RE = re.compile(r"^\d{1,2}\.\d{1,2}(\.\d{1,2})?([-+][0-9A-Za-z.\-]+)?$")
SCENARIO_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_./-]{0,63}$")
EPOCH_SKEW_ALLOW_SECONDS = 600

# Minimum corpus gates for ANY metric/training run. Deliberately conservative.
GATE_MIN_USABLE = 200
GATE_MIN_CHEAT = 50
GATE_MIN_LEGIT = 50

REQUIRED_FIELDS = (
    "player_pseudonym", "session_pseudonym", "mc_version", "client_category",
    "input_category", "tps_1m", "ping_ms", "feature_schema_hash",
    "label", "label_source", "label_confidence", "collected_utc", "scenario", "features",
)


class SampleError(ValueError):
    """One row is invalid; carries a stable machine-readable reason."""

    def __init__(self, reason: str, detail: str = ""):
        super().__init__(f"{reason}: {detail}" if detail else reason)
        self.reason = reason


@dataclass
class Sample:
    player_pseudonym: str
    session_pseudonym: str
    mc_version: str
    client_category: str
    input_category: str
    tps_1m: float
    ping_ms: float
    feature_schema_hash: str
    label: str
    label_source: str
    label_confidence: float
    collected_utc: str
    scenario: str
    features: list[float]
    provenance_note: str = ""

    @staticmethod
    def from_row(row: object) -> "Sample":
        if not isinstance(row, dict):
            raise SampleError("row_not_object")
        missing = [f for f in REQUIRED_FIELDS if f not in row]
        if missing:
            raise SampleError("missing_fields", ",".join(missing))
        s = row
        _require_str(s, "player_pseudonym", PSEUDONYM_RE, "bad_player_pseudonym")
        _require_str(s, "session_pseudonym", PSEUDONYM_RE, "bad_session_pseudonym")
        _require_str(s, "mc_version", MC_VERSION_RE, "bad_mc_version")
        client_category = s["client_category"]
        if not isinstance(client_category, str) or not client_category or len(client_category) > 64:
            raise SampleError("bad_client_category")
        input_category = s["input_category"]
        if input_category not in INPUT_CATEGORIES:
            raise SampleError("bad_input_category", str(input_category))
        tps = _require_num(s, "tps_1m", 0.0, 20.0)
        ping = _require_num(s, "ping_ms", 0.0, 5000.0)
        fsh = s["feature_schema_hash"]
        if not isinstance(fsh, str) or fsh.lower() != SCHEMA_HASH:
            raise SampleError("schema_hash_mismatch", str(fsh)[:16])
        label = s["label"]
        if label not in LABELS:
            raise SampleError("bad_label", str(label))
        source = s["label_source"]
        if source not in LABEL_SOURCES:
            raise SampleError("bad_label_source", str(source))
        confidence = _require_num(s, "label_confidence", 0.0, 1.0)
        if label == "CHEAT_VERIFIED":
            if source not in ("CONTROLLED_LAB", "MODERATOR_REVIEW"):
                raise SampleError("cheat_verified_weak_source", source)
            if confidence < 0.8:
                raise SampleError("cheat_verified_low_confidence", str(confidence))
        collected = s["collected_utc"]
        _parse_utc(collected)
        scenario = s["scenario"]
        if not isinstance(scenario, str) or not SCENARIO_RE.match(scenario):
            raise SampleError("bad_scenario", str(scenario)[:48])
        features = s["features"]
        if not isinstance(features, list) or len(features) != FEATURE_COUNT:
            raise SampleError("bad_feature_count", str(len(features) if isinstance(features, list) else type(features).__name__))
        fv = []
        for i, value in enumerate(features):
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise SampleError("non_numeric_feature", f"features[{i}]")
            x = float(value)
            if math.isnan(x) or math.isinf(x):
                raise SampleError("non_finite_feature", f"features[{i}]")
            lo, hi = RANGES[i]
            if x < lo or x > hi:
                raise SampleError("out_of_range_feature", f"features[{i}]={x}")
            fv.append(x)
        if all(x == 0.0 for x in fv):
            raise SampleError("empty_signal", "all features zero")
        note = s.get("provenance_note", "")
        if not isinstance(note, str) or len(note) > 500:
            raise SampleError("bad_provenance_note")
        return Sample(
            player_pseudonym=s["player_pseudonym"], session_pseudonym=s["session_pseudonym"],
            mc_version=s["mc_version"], client_category=client_category,
            input_category=input_category, tps_1m=tps, ping_ms=ping,
            feature_schema_hash=fsh.lower(), label=label, label_source=source,
            label_confidence=confidence, collected_utc=collected, scenario=scenario,
            features=fv, provenance_note=note,
        )

    def dedup_key(self) -> str:
        payload = json.dumps(
            {"s": self.session_pseudonym, "t": self.collected_utc,
             "f": [round(x, 9) for x in self.features]},
            sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    def sample_key(self) -> str:
        """Stable cross-tool key (Java scorers can reproduce this)."""
        return self.dedup_key()


def _require_str(row: dict, field: str, pattern: re.Pattern, reason: str) -> str:
    value = row[field]
    if not isinstance(value, str) or not pattern.match(value):
        raise SampleError(reason, str(value)[:48])
    return value


def _require_num(row: dict, field: str, lo: float, hi: float) -> float:
    value = row[field]
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise SampleError(f"bad_{field}")
    x = float(value)
    if math.isnan(x) or math.isinf(x) or x < lo or x > hi:
        raise SampleError(f"bad_{field}", str(value))
    return x


def _parse_utc(value: str) -> datetime:
    if not isinstance(value, str):
        raise SampleError("bad_collected_utc")
    try:
        parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    except ValueError:
        raise SampleError("bad_collected_utc", value[:32])
    now = datetime.now(timezone.utc)
    if (parsed - now).total_seconds() > EPOCH_SKEW_ALLOW_SECONDS:
        raise SampleError("future_collected_utc", value)
    return parsed


def iter_jsonl(path: Path) -> Iterator[tuple[int, object]]:
    with path.open("r", encoding="utf-8") as handle:
        for lineno, line in enumerate(handle, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                yield lineno, json.loads(line)
            except json.JSONDecodeError as exc:
                yield lineno, SampleError("invalid_json", str(exc)[:64])


def corpus_files(corpus_dir: Path) -> list[Path]:
    return sorted(p for p in corpus_dir.glob("*.jsonl") if p.is_file())


@dataclass
class IngestReport:
    accepted: list[Sample]
    rejected: list[tuple[str, int, str]]  # (file, line, reason)
    duplicates: int

    def counts_by(self, key: str) -> dict[str, int]:
        out: dict[str, int] = {}
        for sample in self.accepted:
            out[getattr(sample, key)] = out.get(getattr(sample, key), 0) + 1
        return dict(sorted(out.items()))


def load_corpus(corpus_dir: Path, *, drop_duplicates: bool = True) -> IngestReport:
    accepted: list[Sample] = []
    rejected: list[tuple[str, int, str]] = []
    seen: set[str] = set()
    duplicates = 0
    for path in corpus_files(corpus_dir):
        for lineno, row in iter_jsonl(path):
            if isinstance(row, SampleError):
                rejected.append((path.name, lineno, row.reason))
                continue
            try:
                sample = Sample.from_row(row)
            except SampleError as exc:
                rejected.append((path.name, lineno, exc.reason))
                continue
            key = sample.dedup_key()
            if key in seen:
                duplicates += 1
                if drop_duplicates:
                    continue
            seen.add(key)
            accepted.append(sample)
    return IngestReport(accepted=accepted, rejected=rejected, duplicates=duplicates)


def corpus_digest(corpus_dir: Path) -> str:
    """SHA-256 over sorted 'sha256  filename' lines — stable across runs."""
    digest = hashlib.sha256()
    for path in corpus_files(corpus_dir):
        file_hash = hashlib.sha256(path.read_bytes()).hexdigest()
        digest.update(f"{file_hash}  {path.name}\n".encode("utf-8"))
    return digest.hexdigest()


def split_assignment(player_pseudonym: str, seed: int,
                     train_ratio: float = 0.70, val_ratio: float = 0.15) -> str:
    """Deterministic group split by player. Same player ⇒ same split, always."""
    fraction = int(hashlib.sha256(f"{seed}:{player_pseudonym}".encode("utf-8")).hexdigest(), 16) / ((1 << 256) - 1)
    if fraction < train_ratio:
        return "train"
    if fraction < train_ratio + val_ratio:
        return "val"
    return "test"


def split_corpus(samples: Iterable[Sample], seed: int,
                 train_ratio: float = 0.70, val_ratio: float = 0.15) -> dict[str, list[Sample]]:
    splits: dict[str, list[Sample]] = {"train": [], "val": [], "test": []}
    for sample in samples:
        splits[split_assignment(sample.player_pseudonym, seed, train_ratio, val_ratio)].append(sample)
    return splits


def assert_no_leakage(splits: dict[str, list[Sample]]) -> None:
    players = {name: {s.player_pseudonym for s in rows} for name, rows in splits.items()}
    sessions = {name: {s.session_pseudonym for s in rows} for name, rows in splits.items()}
    names = list(splits)
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            overlap_p = players[names[i]] & players[names[j]]
            overlap_s = sessions[names[i]] & sessions[names[j]]
            if overlap_p:
                raise AssertionError(f"player leakage between {names[i]} and {names[j]}: {sorted(overlap_p)[:3]}")
            if overlap_s:
                raise AssertionError(f"session leakage between {names[i]} and {names[j]}: {sorted(overlap_s)[:3]}")


def evaluation_rows(samples: Iterable[Sample]) -> list[Sample]:
    """Rows usable for detection metrics: LEGITIMATE vs CHEAT_VERIFIED only."""
    return [s for s in samples if s.label in ("LEGITIMATE", "CHEAT_VERIFIED")]


def corpus_gates(samples: Iterable[Sample]) -> tuple[bool, str]:
    rows = evaluation_rows(samples)
    legit = sum(1 for s in rows if s.label == "LEGITIMATE")
    cheat = sum(1 for s in rows if s.label == "CHEAT_VERIFIED")
    if len(rows) < GATE_MIN_USABLE or cheat < GATE_MIN_CHEAT or legit < GATE_MIN_LEGIT:
        return False, (f"INSUFFICIENT_DATA: usable={len(rows)} (need {GATE_MIN_USABLE}), "
                       f"cheat_verified={cheat} (need {GATE_MIN_CHEAT}), legit={legit} (need {GATE_MIN_LEGIT})")
    return True, f"OK: usable={len(rows)}, cheat_verified={cheat}, legit={legit}"


def wilson_interval(successes: int, total: int, z: float = 1.959964) -> tuple[float, float]:
    if total <= 0:
        return (0.0, 1.0)
    p = successes / total
    denom = 1.0 + z * z / total
    center = (p + z * z / (2 * total)) / denom
    margin = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / denom
    return (max(0.0, center - margin), min(1.0, center + margin))


def compute_metrics(y_true: list[int], y_score: list[float], threshold: float) -> dict:
    """Model-agnostic metrics. y_true: 1=CHEAT_VERIFIED, 0=LEGITIMATE."""
    if len(y_true) != len(y_score):
        raise ValueError("y_true and y_score length mismatch")
    tp = fp = tn = fn = 0
    for truth, score in zip(y_true, y_score):
        predicted = 1 if score >= threshold else 0
        if predicted == 1 and truth == 1:
            tp += 1
        elif predicted == 1 and truth == 0:
            fp += 1
        elif predicted == 0 and truth == 0:
            tn += 1
        else:
            fn += 1
    precision = tp / (tp + fp) if (tp + fp) else None
    recall = tp / (tp + fn) if (tp + fn) else None
    f1 = (2 * precision * recall / (precision + recall)
          if precision is not None and recall is not None and (precision + recall) else None)
    fpr = fp / (fp + tn) if (fp + tn) else None
    return {
        "threshold": threshold,
        "confusion_matrix": {"tn": tn, "fp": fp, "fn": fn, "tp": tp},
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "false_positive_rate": fpr,
        "precision_wilson95": wilson_interval(tp, tp + fp),
        "recall_wilson95": wilson_interval(tp, tp + fn),
        "fpr_wilson95": wilson_interval(fp, fp + tn),
        "support": {"legit": tn + fp, "cheat_verified": tp + fn},
    }
